CREATE OR REPLACE DYNAMIC TABLE ANALYTICS.DT_CUSTOMER_360
    TARGET_LAG = '30 minutes' WAREHOUSE = WH_INSURE360_APP
AS
WITH policy_agg AS (
    SELECT CUSTOMER_ID,
        COUNT(DISTINCT POLICY_ID) AS TOTAL_POLICIES,
        COUNT(DISTINCT CASE WHEN POLICY_STATUS = 'ACTIVE' THEN POLICY_ID END) AS ACTIVE_POLICIES,
        COUNT(DISTINCT CASE WHEN POLICY_STATUS = 'LAPSED' THEN POLICY_ID END) AS LAPSED_POLICIES,
        ARRAY_AGG(DISTINCT POLICY_TYPE) AS POLICY_TYPES,
        COALESCE(SUM(SUM_INSURED), 0) AS TOTAL_SUM_INSURED,
        COALESCE(SUM(CASE WHEN POLICY_STATUS = 'ACTIVE' THEN ANNUAL_PREMIUM ELSE 0 END), 0) AS TOTAL_ANNUAL_PREMIUM,
        MIN(CASE WHEN POLICY_STATUS = 'ACTIVE' AND EXPIRY_DATE > CURRENT_DATE() THEN EXPIRY_DATE END) AS NEXT_RENEWAL_DATE
    FROM INSURE360_APP.INTERFACE.V_POLICIES GROUP BY CUSTOMER_ID
),
claims_agg AS (
    SELECT CUSTOMER_ID,
        COUNT(DISTINCT CLAIM_ID) AS TOTAL_CLAIMS,
        COUNT(DISTINCT CASE WHEN CLAIM_STATUS NOT IN ('SETTLED','CLOSED','REJECTED') THEN CLAIM_ID END) AS OPEN_CLAIMS,
        COALESCE(SUM(CLAIM_AMOUNT), 0) AS TOTAL_CLAIM_AMOUNT,
        COALESCE(SUM(APPROVED_AMOUNT), 0) AS TOTAL_APPROVED_AMOUNT,
        MAX(CASE WHEN FRAUD_FLAG IN ('Y','SUSPECT') THEN TRUE ELSE FALSE END) AS HAS_FRAUD_FLAG
    FROM INSURE360_APP.INTERFACE.V_CLAIMS GROUP BY CUSTOMER_ID
)
SELECT c.CUSTOMER_ID, CONCAT(c.FIRST_NAME, ' ', c.LAST_NAME) AS CUSTOMER_NAME,
    DATEDIFF('YEAR', c.DATE_OF_BIRTH, CURRENT_DATE()) AS AGE, c.GENDER, c.CITY, c.STATE,
    c.CUSTOMER_SEGMENT, DATEDIFF('MONTH', c.ONBOARDING_DATE, CURRENT_DATE()) AS CUSTOMER_TENURE_MONTHS,
    c.PREFERRED_CHANNEL,
    COALESCE(p.TOTAL_POLICIES, 0) AS TOTAL_POLICIES, COALESCE(p.ACTIVE_POLICIES, 0) AS ACTIVE_POLICIES,
    COALESCE(p.LAPSED_POLICIES, 0) AS LAPSED_POLICIES, p.POLICY_TYPES,
    COALESCE(p.TOTAL_SUM_INSURED, 0) AS TOTAL_SUM_INSURED, COALESCE(p.TOTAL_ANNUAL_PREMIUM, 0) AS TOTAL_ANNUAL_PREMIUM,
    p.NEXT_RENEWAL_DATE, DATEDIFF('DAY', CURRENT_DATE(), p.NEXT_RENEWAL_DATE) AS DAYS_TO_RENEWAL,
    COALESCE(cl.TOTAL_CLAIMS, 0) AS TOTAL_CLAIMS, COALESCE(cl.OPEN_CLAIMS, 0) AS OPEN_CLAIMS,
    COALESCE(cl.TOTAL_CLAIM_AMOUNT, 0) AS TOTAL_CLAIM_AMOUNT, COALESCE(cl.TOTAL_APPROVED_AMOUNT, 0) AS TOTAL_APPROVED_AMOUNT,
    COALESCE(cl.HAS_FRAUD_FLAG, FALSE) AS HAS_FRAUD_FLAG, CURRENT_TIMESTAMP() AS LAST_REFRESHED
FROM INSURE360_APP.INTERFACE.V_CUSTOMERS c
LEFT JOIN policy_agg p ON c.CUSTOMER_ID = p.CUSTOMER_ID
LEFT JOIN claims_agg cl ON c.CUSTOMER_ID = cl.CUSTOMER_ID
WHERE c.IS_ACTIVE = TRUE;


