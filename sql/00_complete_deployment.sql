CREATE OR REPLACE PROCEDURE CONFIG.GENERATE_INTERFACE_VIEW(P_INTERFACE_NAME VARCHAR)
RETURNS VARCHAR LANGUAGE SQL EXECUTE AS CALLER
AS
$$
DECLARE
    v_iface VARCHAR DEFAULT P_INTERFACE_NAME;
    v_sql TEXT; v_select_list TEXT DEFAULT ''; v_from_clause TEXT DEFAULT '';
    v_base_table TEXT; v_base_filter TEXT; v_has_value_map INT;
    v_value_case TEXT; v_col_name VARCHAR; v_col_expr VARCHAR; v_col_default VARCHAR;
    cur_columns CURSOR FOR
        SELECT ic.COLUMN_NAME, ic.DEFAULT_EXPRESSION, cm.SOURCE_EXPRESSION
        FROM INSURE360_APP.CONFIG.INTERFACE_CONTRACTS ic
        LEFT JOIN INSURE360_APP.CONFIG.COLUMN_MAPPING cm
            ON ic.INTERFACE_NAME = cm.INTERFACE_NAME AND ic.COLUMN_NAME = cm.INTERFACE_COLUMN AND cm.IS_ACTIVE = TRUE
        WHERE ic.INTERFACE_NAME = ? ORDER BY ic.COLUMN_ORDER;
BEGIN
    SELECT CONCAT(SOURCE_DATABASE, '.', SOURCE_SCHEMA, '.', SOURCE_TABLE), SOURCE_FILTER
    INTO :v_base_table, :v_base_filter
    FROM INSURE360_APP.CONFIG.SOURCE_TABLE_MAPPING
    WHERE INTERFACE_NAME = :v_iface AND IS_ACTIVE = TRUE AND JOIN_ORDER = 0 LIMIT 1;
    IF (v_base_table IS NULL) THEN RETURN CONCAT('ERROR: No base table mapped for ', :v_iface); END IF;
    v_from_clause := CONCAT(v_base_table, ' T0');
    OPEN cur_columns USING (:v_iface);
    FOR col_rec IN cur_columns DO
        v_col_name := col_rec.COLUMN_NAME; v_col_expr := col_rec.SOURCE_EXPRESSION; v_col_default := col_rec.DEFAULT_EXPRESSION;
        LET final_expr TEXT;
        IF (v_col_expr IS NOT NULL) THEN
            final_expr := v_col_expr;
            SELECT COUNT(*) INTO :v_has_value_map FROM INSURE360_APP.CONFIG.VALUE_MAPPING WHERE INTERFACE_NAME = :v_iface AND INTERFACE_COLUMN = :v_col_name;
            IF (v_has_value_map > 0) THEN
                SELECT LISTAGG(CASE WHEN IS_DEFAULT THEN CONCAT(' ELSE ''', TARGET_VALUE, '''') ELSE CONCAT(' WHEN ''', SOURCE_VALUE, ''' THEN ''', TARGET_VALUE, '''') END, '') WITHIN GROUP (ORDER BY IS_DEFAULT) INTO :v_value_case FROM INSURE360_APP.CONFIG.VALUE_MAPPING WHERE INTERFACE_NAME = :v_iface AND INTERFACE_COLUMN = :v_col_name;
                final_expr := CONCAT('CASE ', final_expr, v_value_case, ' END');
            END IF;
        ELSEIF (v_col_default IS NOT NULL) THEN final_expr := v_col_default;
        ELSE final_expr := 'NULL'; END IF;
        IF (LENGTH(v_select_list) > 0) THEN v_select_list := CONCAT(v_select_list, ', '); END IF;
        v_select_list := CONCAT(v_select_list, final_expr, ' AS ', v_col_name);
    END FOR;
    IF (v_base_filter IS NOT NULL AND LENGTH(v_base_filter) > 0) THEN
        v_sql := CONCAT('CREATE OR REPLACE VIEW INSURE360_APP.INTERFACE.', :v_iface, ' AS SELECT ', v_select_list, ' FROM ', v_from_clause, ' WHERE ', v_base_filter);
    ELSE
        v_sql := CONCAT('CREATE OR REPLACE VIEW INSURE360_APP.INTERFACE.', :v_iface, ' AS SELECT ', v_select_list, ' FROM ', v_from_clause);
    END IF;
    EXECUTE IMMEDIATE v_sql;
    UPDATE INSURE360_APP.CONFIG.ONBOARDING_STATUS SET MAPPING_STATUS = 'ACTIVE', LAST_GENERATED_AT = CURRENT_TIMESTAMP(), UPDATED_AT = CURRENT_TIMESTAMP() WHERE INTERFACE_NAME = :v_iface;
    RETURN CONCAT('SUCCESS: INSURE360_APP.INTERFACE.', :v_iface);
END;
$$;


